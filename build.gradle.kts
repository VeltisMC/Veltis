/**
 * How many files of one category the patch set addresses, read from the manifest
 * the patcher writes. Used only in a build log line.
 */
fun patchTargetCount(category: String): Int {
    val manifest = patchTargetsFile.asFile
    if (!manifest.isFile) return 0
    return manifest.readLines().count { it.startsWith("$category\t") }
}

