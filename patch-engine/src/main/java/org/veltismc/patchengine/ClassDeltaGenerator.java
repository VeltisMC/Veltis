    private static ClassNode parse(byte[] bytes, String target) {
        var node = new ClassNode();
        try {
            new ClassReader(bytes).accept(node, 0);
        } catch (RuntimeException e) {
            throw mismatch(target, "cannot be read as a class file",
                MojangMetadata.rootMessage(e));
        }
        return node;
    }

    /** Parses without debug information, for comparison and verification. */
    private static ClassNode parseCompare(byte[] bytes, String target) {
        var node = new ClassNode();
        try {
            new ClassReader(bytes).accept(node, ClassReader.SKIP_DEBUG);
        } catch (RuntimeException e) {
            throw mismatch(target, "cannot be read as a class file",
                MojangMetadata.rootMessage(e));
        }
        return node;
    }

    private static PatchEngineException mismatch(String target, String detail, String reason) {
        return new PatchEngineException(
            "[Veltis] The class delta for " + target + " " + detail
                + "\n  Reason: " + reason
                + "\n  The patch set was not written."
                + "\n  Fix: regenerate the patch set.");
    }
