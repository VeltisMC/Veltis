    val target = packagedVersionFile
    inputs.property("minecraftVersion", minecraftVersion)
    outputs.file(target).withPropertyName("packagedVersion")
    doLast {
        val file = target.get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            # Generated by the VeltisMC build. The version java -jar veltismc.jar
            # builds for when --version is not given.
            $minecraftVersion
            """.trimIndent() + "\n"
        )
    }
}

/**
 * Records the minimum Java release the packaged server runs on.
 *
 * <p>Written from the same {@code veltisJavaRelease} the compiler targets, so
 * the runtime version guard the launcher executes and the class files it is
 * about to load are guaranteed to agree. The guard is compiled to Java 8 so it
 * can run on a JVM too old to load anything else in the jar, and it reads this
 * file rather than carrying a constant that could drift.
 */
val writePackagedJavaVersion by tasks.registering {
    group = "minecraft"
    description = "Records the minimum Java release the packaged server is compiled for"
    val target = packagedJavaVersionFile
    inputs.property("veltisJavaRelease", veltisJavaRelease)
    outputs.file(target).withPropertyName("packagedJavaVersion")
    doLast {
        val file = target.get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            # Generated by the VeltisMC build. The minimum Java feature release
            # java -jar veltismc.jar runs on; the class files in this jar are
            # compiled for exactly this release. Read by JavaVersionGuard before
            # any other class is loaded.
            $veltisJavaRelease
            """.trimIndent() + "\n"
        )
    }
}

// ---------------------------------------------------------------------------
// Pipeline steps
//
// Every step is a JavaExec with declared inputs and outputs, so Gradle can skip
// work that is genuinely done and rerun work that is not. The steps themselves
// are thin wrappers around patch-engine (see patch-engine/PipelineRunner).
// ---------------------------------------------------------------------------
fun pipelineStep(
    name: String,
    step: String,
    description: String,
) = tasks.register<JavaExec>(name) {
    this.group = "minecraft"
    this.description = description
    classpath = pipelineClasspath
    mainClass = "org.veltismc.patchengine.PipelineRunner"
    javaLauncher.set(pipelineLauncher)
    // patchWorkers is used by the patching step and the release by the compile
    // step; each step ignores the argument it does not use.
    args(step, minecraftVersion, rootDir.absolutePath, patchWorkers.toString(),
        veltisJavaRelease.toString())
    dependsOn(":patch-engine:classes")
    // Any change to the pipeline code itself must invalidate the pipeline's
    // own outputs, otherwise a fix to the patcher would not take effect until
    // something unrelated changed.
    inputs.files(pipelineClasspath).withPropertyName("pipelineClasspath")
    // `-PveltisPipelineDebug` adds the Java stack trace to a failure. The
    // engine's own messages are written to be readable on their own, but a
    // message that comes from deep inside the JDK or a decompiler is not, and
    // without a stack there is nowhere to look. The same flag also turns the
    // pipeline JVMs' root logger to DEBUG: every preparation diagnostic the
    // engine prints is DEBUG (normal server startup shows only the bootstrap
    // lines), and the build's phase timings are behind this flag.
    if (providers.gradleProperty("veltisPipelineDebug").isPresent) {
        systemProperty("veltismc.debug", "true")
        systemProperty("veltis.log.level", "DEBUG")
    }
}

val downloadMinecraft = pipelineStep(
    "downloadMinecraft", "downloadMinecraft",
    "Resolves Minecraft $minecraftVersion on Mojang and verifies every artifact's SHA-1"
).also {
    it.configure {
        inputs.property("minecraftVersion", minecraftVersion)
        // Declaring the manifest URL as an input is what makes a change to the
        // acquisition endpoint re-run the download.
        // The classes jar alongside the bundler jar: it is extracted from the
        // bundler rather than downloaded separately, and it is the baseline the
        // bytecode patch set is cut from, so a build that does not know about it
        // would treat a required input as a stray file.
        outputs.files(versionMetadataFile, libraryCoordinatesFile, vanillaServerJar,
            vanillaClassesJar)
            .withPropertyName("minecraftArtifacts")
    }
}

val downloadLibraries = pipelineStep(
    "downloadLibraries", "downloadLibraries",
    "Fetches the library jars Mojang declares for $minecraftVersion"
).also {
    it.configure {
        inputs.files(versionMetadataFile, libraryCoordinatesFile)
            .withPropertyName("declarationInputs")
        inputs.property("minecraftVersion", minecraftVersion)
        outputs.dir(librariesDir).withPropertyName("minecraftLibraries")
        // Never skipped. Gradle decides a directory output is unchanged by
        // comparing it with its recorded snapshot, and an earlier step recreates
        // libraries/ as an empty directory before this check runs -- so on a fresh
        // clone Gradle saw an empty tree, called it up to date, and the build
        // carried on with no libraries at all. There is no honest predicate
        // available here either: metadata/libraries.txt lists the 56 resolvable
        // module coordinates, not the 114 artifact files actually fetched, so a
        // directory count cannot prove the tree is complete.
        //
        // The step is idempotent and cheap when warm: it SHA-1 verifies each
        // cached jar and fetches nothing, which measures ~370ms. Paying that to
        // remove a way to silently ship an empty classpath is the right trade.
        outputs.upToDateWhen { false }
        dependsOn(downloadMinecraft)
    }
}

/**
 * Widens class, field and method access in the verified class jar.
 *
 * <p>This runs before the decompile, not after it, and that ordering is the
 * whole point: the decompiled source is compiled against the widened jar, so a
 * method Mojang declared `protected` is `public` in both. Decompiling the
 * un-widened jar instead produces sources that cannot be compiled over the
 * widened classes at all — "attempting to assign weaker access privileges" on
 * every override the patch set touches.
 */
val widenServerJarAccess = pipelineStep(
    "widenServerJarAccess", "widenServerJarAccess",
    "Widens class/field/method access in the verified server jar"
).also {
    it.configure {
        // Before the decompile, not after it, and that ordering is the whole
        // point: the decompiled source is compiled against the widened jar, so a
        // method Mojang declared `protected` is `public` in both. Decompiling the
        // un-widened jar instead produces sources that cannot be compiled over the
        // widened classes at all — "attempting to assign weaker access privileges"
        // on every override the patch set touches.
        inputs.file(vanillaClassesJar).withPropertyName("serverClassesJar")
        outputs.file(widenedServerJar).withPropertyName("widenedServerJar")
        dependsOn(downloadMinecraft)
    }
}

val decompileMinecraft = pipelineStep(
    "decompileMinecraft", "decompileMinecraft",
    "Decompiles the verified server jar into the workspace's pristine source tree"
).also {
    it.configure {
        inputs.files(widenedServerJar, libraryCoordinatesFile)
            .withPropertyName("decompileInputs")
        outputs.dir(sourceDir).withPropertyName("decompiledSource")
        dependsOn(downloadLibraries, widenServerJarAccess)
    }
}

val applyVeltisPatches = pipelineStep(
    "applyVeltisPatches", "applyVeltisPatches",
    "Mirrors the decompiled source and applies server/Shulker/{code,data,modules}"
).also {
    it.configure {
        inputs.dir(patchesDir).withPropertyName("patchSet")
        inputs.dir(sourceDir).withPropertyName("decompiledSource")
        inputs.property("minecraftVersion", minecraftVersion)
        inputs.property("patchWorkers", patchWorkers)
        outputs.dir(patchedDir).withPropertyName("patchedSource")
        outputs.file(patchTargetsFile).withPropertyName("patchTargets")
        dependsOn(decompileMinecraft)
    }
}

val rebuildVeltisPatches = pipelineStep(
    "rebuildVeltisPatches", "rebuildVeltisPatches",
    "Regenerates server/Shulker/ from the current contents of the patched workspace"
).also {
    it.configure {
        // Deliberately NOT dependsOn(applyVeltisPatches). The rebuild workflow is
        // "edit a file in patched/ in the IDE, then run this task", and apply
        // re-mirrors the pristine source over patched/ with REPLACE_EXISTING --
        // so depending on it would discard the very edits being captured, and the
        // rebuild would diff a tree it had just overwritten. Only the pristine
        // baseline is needed here, which is decompileMinecraft's output.
        dependsOn(decompileMinecraft)

        // patched/ is hand-edited between runs, so its contents cannot be tracked
        // as an input: Gradle would either miss a change or consider the task up to
        // date while server/Shulker/ is stale. Reading the tree live and always running is
        // the only honest description of what this task does.
        outputs.upToDateWhen { false }
        outputs.dir(patchesDir).withPropertyName("regeneratedPatches")

        // -PpatchName="Improve Entity Logging" names the one patch this rebuild
        // creates instead of the name derived from the target path. A system
        // property rather than a fifth argument so the pipeline's step signature
        // stays (step, version, root, workers) for every other task, and the
        // rebuilder is the one place that decides what a name means.
        providers.gradleProperty("patchName").orNull?.let { requested ->
            systemProperty("veltismc.patchName", requested)
        }
    }
}

val cleanVeltisPatches = pipelineStep(
    "cleanVeltisPatches", "cleanVeltisPatches",
    "Discards the patched workspace and its compiled output"
).also {
    it.configure {
        // A clean task is meaningless if it can be up to date.
        outputs.upToDateWhen { false }
        outputs.dir(patchedDir).withPropertyName("patchedSource")
        outputs.dir(classesDir).withPropertyName("minecraftClasses")
        outputs.dir(resourcesDir).withPropertyName("minecraftResources")
    }
}

/**
 * The two commands a contributor actually types, as aliases of the pipeline's
 * own names.
 *
 * <p>Both spellings run the same task, so nothing is duplicated and nothing can
 * drift: `applyPatches` is `applyVeltisPatches`, and `rebuildPatches` is
 * `rebuildVeltisPatches`. The shorter pair is what CONTRIBUTING.md documents
 * because it is what reads like an instruction; the longer pair stays because
 * CI, the README and the engine's own log lines already use it, and renaming
 * them would break both for no gain.
 */
tasks.register("applyPatches") {
    group = "minecraft"
    description = "Mirrors the pristine decompiled source and applies server/Shulker/{code,data,modules}"
    dependsOn(applyVeltisPatches)
}

tasks.register("rebuildPatches") {
    group = "minecraft"
    description = "Turns edited files under patched/ back into server/Shulker/, renumbered contiguously"
    dependsOn(rebuildVeltisPatches)
}

/**
 * The whole chain, in one call, through the code the launcher runs.
 *
 * <p>This is the build's answer to "make the runtime ready", and it is the same
 * `VeltisRuntime.prepare()` a cold `java -jar veltismc.jar` calls. One
 * implementation, two callers — which is the point. A separate Gradle
 * composition of download/decompile/patch/compile tasks could drift from what a
 * server actually does, and the drift would show up as a jar that builds fine
 * and starts vanilla. The fine-grained tasks below still exist and still run:
 * they are what an IDE and a developer use to walk one stage at a time.
 *
 * <p>The engine keeps its own per-stage validity rules, so this task is skipped
 * only when the marker it writes still matches the version, the artifact hash,
 * the patch revision and the compiler release.
 */
val prepareVeltisRuntime = pipelineStep(
    "prepareVeltisRuntime", "prepareVeltisRuntime",
    "Builds the patched runtime exactly as the launcher does, and records its identity"
).also {
    it.configure {
        inputs.dir(patchesDir).withPropertyName("patchSet")
        inputs.property("minecraftVersion", minecraftVersion)
        inputs.property("patchWorkers", patchWorkers)
        inputs.property("classFileRelease", veltisJavaRelease)
        // The whole workspace is this task's output, because this task can build
        // all of it: it resolves, downloads, verifies, widens, decompiles, patches
        // and compiles for itself, each stage behind its own cache. Declaring only
        // classes/ would leave the download and decompile stages looking like
        // outputs of the per-stage tasks, whose ordering this task does not and
        // should not depend on.
        outputs.dir(vanillaDir).withPropertyName("vanillaArtifacts")
        outputs.dir(metadataDir).withPropertyName("minecraftMetadata")
        outputs.dir(librariesDir).withPropertyName("minecraftLibraries")
        outputs.dir(sourceDir).withPropertyName("decompiledSource")
        outputs.dir(patchedDir).withPropertyName("patchedSource")
        outputs.dir(classesDir).withPropertyName("patchedClasses")
        outputs.dir(resourcesDir).withPropertyName("patchedResources")
        outputs.dir(buildStateDir).withPropertyName("pipelineState")
        outputs.file(runtimeMarkerFile).withPropertyName("runtimeIdentity")
        outputs.dir(runtimePatchesDir).withPropertyName("runtimePatches")
        // The patched runtime artifact: the same jar the launcher runs and the
        // same one :server's classpath hands javac and the IDE. Declared so a
        // deleted or stale artifact re-runs the build instead of the compiler
        // silently reading last week's classes.
        outputs.file(veltisServerJar).withPropertyName("veltisServerJar")

        // The per-stage tasks and this one both produce the workspace, which Gradle
        // will call an overlapping output and refuse to cache. It is a real
        // duplication, and the ordering below is what keeps it harmless: when a
        // developer asks for both in one invocation (`prepareMinecraft
        // buildVeltisMC`) the per-stage chain runs first and this task then finds
        // every stage cached, so it reduces to the compile and the identity. The
        // alternative — making this task depend on the per-stage chain — would
        // mean the launcher and the build no longer share one implementation.
        mustRunAfter(downloadMinecraft, downloadLibraries, widenServerJarAccess,
            decompileMinecraft, applyVeltisPatches, rebuildVeltisPatches)
    }
}

/**
 * Fails the build unless the runtime really loads its patched classes.
 *
 * <p>Replaces the old check that unpacked the pre-packaged server jar and
 * compared bytes. That check could only prove a class was present in an
 * archive; the
 * failure it guards against is a classpath decision — vanilla winning because an
 * entry was ordered differently, or because a library shadowed it. This one
 * builds the loader the server will use and asks it where each patched class
 * resolves from and whether the bytes are patched.
 *
 * <p>Three layers instead of one, because each catches a different mistake:
 * the compiled class exists, it differs from vanilla (so no patch silently
 * applied nothing), and the loader serves exactly those bytes.
 */
val verifyVeltisRuntime = pipelineStep(
    "verifyVeltisRuntime", "verifyVeltisRuntime",
    "Proves the runtime classpath loads the patched classes and not the vanilla ones"
).also {
    it.configure {
        // The classpath input is declared by pipelineStep; only the dependency on
        // what it verifies is this task's own.
        dependsOn(prepareVeltisRuntime)
        // `-PveltisGuardCanary` reverses the classpath on purpose so the guard's
        // failure can be demonstrated rather than asserted. Forwarded explicitly
        // because a Gradle property is not a system property: without this the run
        // reports success and proves nothing, which is the one outcome a canary
        // must never produce.
        if (providers.gradleProperty("veltisGuardCanary").isPresent) {
            systemProperty("veltisGuardCanary", "true")
        }
    }
}

/**
 * Publishes the bytecode patch set into the resources the launcher jar is built
 * from.
 *
 * <p>This is the one thing that makes `java -jar server.jar` a complete
 * distribution: the patch set that turns a downloaded vanilla jar into a
 * VeltisMC server travels inside the launcher, under a name that says which
 * Minecraft version it addresses. An operator never has a `Shulker/` directory,
 * a Git checkout, a decompiler or a compiler, and never needs one.
 *
 * <p>Generated rather than assembled by the packaging script, so the file that
 * ships is the file the applier reads back and re-validates — a patch set that
 * this build could not read would fail here instead of on a stranger's machine.
 */
val publishBytecodePatch by tasks.registering {
    group = "minecraft"
    description = "Publishes the bytecode patch set the launcher jar distributes"
    val source = workspaceDir.file("build/veltis-patch.zip")
    inputs.file(source).withPropertyName("bytecodePatchSet")
    inputs.property("minecraftVersion", minecraftVersion)
    outputs.file(generatedPatchFile).withPropertyName("publishedPatchSet")
    dependsOn(prepareVeltisRuntime)
    doLast {
        val target = generatedPatchFile.get().asFile
        val version = "$minecraftVersion"
        target.parentFile.mkdirs()
        Files.copy(
            source.asFile.toPath(),
            target.toPath(),
            StandardCopyOption.REPLACE_EXISTING,
        )
        logger.lifecycle(
            "Published {} ({} bytes) as META-INF/veltis/patches/{}.zip",
            source.asFile,
            target.length(),
            version,
        )
    }
}

/**
 * The per-stage chain, for an IDE and for a developer working on patches.
 *
 * <p>Not on the production path: `prepareVeltisRuntime` above builds the same
 * result through the engine's own staging, and `compileMinecraftJava` exists so
 * IntelliJ can resolve, navigate and debug the patched sources with a real
 * Gradle compile classpath rather than a folder someone marked by hand.
 */
val prepareMinecraft by tasks.registering {
    group = "minecraft"
    description = "Downloads, decompiles, patches and compiles Minecraft $minecraftVersion (IDE path)"
    dependsOn(applyVeltisPatches, ":compileMinecraftJava", processMinecraftResources)
}

