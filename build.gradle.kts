}

/**
 * Compiles the patched Minecraft sources.
 *
 * <p>Kept alongside `prepareVeltisRuntime`, which compiles the same files through
 * `javax.tools`. This task exists for the IDE and for a developer who wants to
 * step through patched code with a debugger attached to a Gradle-compiled class
 * file; the production path is the engine's in-process compiler, so there is
 * exactly one compile on `buildVeltisMC`.
 *
 * <p>Output goes to this source set's own directory rather than to the runtime's
 * {@code classes/}. The engine owns that one; two tasks writing it would be
 * either an ordering hazard or a Gradle validation failure, and the only thing
 * gained by sharing it is a second copy of the same class files.
 *
 * <p>Only the patched .java files reach javac. Decompiling Minecraft does not
 * produce sources that compile wholesale — 111 of them still contain Vineflower's
 * `<unrepresentable>` placeholder — and compiling all ~15 000 to discover that
 * buries the real errors in noise. Unpatched classes come from the widened jar,
 * so this task's output is exactly the delta the patches introduce.
 */
