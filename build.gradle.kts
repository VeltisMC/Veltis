/**
 * The whole chain, in one call, through the code the launcher runs.
 *
 * <p>This is the build's answer to "make the runtime ready", and it is the same
 * `VeltisRuntime.prepare()` a cold `java -jar veltismc.jar` calls. One
 * implementation, two callers — which is the point. A separate Gradle
 * composition of download/decompile/patch/compile tasks could drift from what a
 * server actually does, and the drift would show up as a jar that builds fine
 * and starts vanilla. The fine-grained tasks below still exist and still run:
 * they are what an IDE and a developer use to walk one stage at a time.
 *
 * <p>The engine keeps its own per-stage validity rules, so this task is skipped
 * only when the marker it writes still matches the version, the artifact hash,
 * the patch revision and the compiler release.
 */
val prepareVeltisRuntime = pipelineStep(
    "prepareVeltisRuntime", "prepareVeltisRuntime",
    "Builds the patched runtime exactly as the launcher does, and records its identity"
).also {
    it.configure {
        inputs.dir(patchesDir).withPropertyName("patchSet")
        inputs.property("minecraftVersion", minecraftVersion)
        inputs.property("patchWorkers", patchWorkers)
        inputs.property("classFileRelease", 26)
        // The whole workspace is this task's output, because this task can build
        // all of it: it resolves, downloads, verifies, widens, decompiles, patches
        // and compiles for itself, each stage behind its own cache. Declaring only
        // classes/ would leave the download and decompile stages looking like
        // outputs of the per-stage tasks, whose ordering this task does not and
        // should not depend on.
        outputs.dir(vanillaDir).withPropertyName("vanillaArtifacts")
        outputs.dir(metadataDir).withPropertyName("minecraftMetadata")
        outputs.dir(librariesDir).withPropertyName("minecraftLibraries")
        outputs.dir(sourceDir).withPropertyName("decompiledSource")
        outputs.dir(patchedDir).withPropertyName("patchedSource")
        outputs.dir(classesDir).withPropertyName("patchedClasses")
        outputs.dir(resourcesDir).withPropertyName("patchedResources")
        outputs.dir(buildStateDir).withPropertyName("pipelineState")
        outputs.file(runtimeMarkerFile).withPropertyName("runtimeIdentity")

        // The per-stage tasks and this one both produce the workspace, which Gradle
        // will call an overlapping output and refuse to cache. It is a real
        // duplication, and the ordering below is what keeps it harmless: when a
        // developer asks for both in one invocation (`prepareMinecraft
        // buildVeltisMC`) the per-stage chain runs first and this task then finds
        // every stage cached, so it reduces to the compile and the identity. The
        // alternative — making this task depend on the per-stage chain — would
        // mean the launcher and the build no longer share one implementation.
        mustRunAfter(downloadMinecraft, downloadLibraries, widenServerJarAccess,
            decompileMinecraft, applyVeltisPatches, rebuildVeltisPatches)
    }
}

/**
 * Fails the build unless the runtime really loads its patched classes.
 *
 * <p>Replaces the old check that unpacked the pre-packaged server jar and
 * compared bytes. That check could only prove a class was present in an
 * archive; the
 * failure it guards against is a classpath decision — vanilla winning because an
 * entry was ordered differently, or because a library shadowed it. This one
 * builds the loader the server will use and asks it where each patched class
 * resolves from and whether the bytes are patched.
 *
 * <p>Three layers instead of one, because each catches a different mistake:
 * the compiled class exists, it differs from vanilla (so no patch silently
 * applied nothing), and the loader serves exactly those bytes.
 */
val verifyVeltisRuntime = pipelineStep(
    "verifyVeltisRuntime", "verifyVeltisRuntime",
    "Proves the runtime classpath loads the patched classes and not the vanilla ones"
).also {
    it.configure {
        // The classpath input is declared by pipelineStep; only the dependency on
        // what it verifies is this task's own.
        dependsOn(prepareVeltisRuntime)
        // `-PveltisGuardCanary` reverses the classpath on purpose so the guard's
        // failure can be demonstrated rather than asserted. Forwarded explicitly
        // because a Gradle property is not a system property: without this the run
        // reports success and proves nothing, which is the one outcome a canary
        // must never produce.
        if (providers.gradleProperty("veltisGuardCanary").isPresent) {
            systemProperty("veltisGuardCanary", "true")
        }
    }
}

/**
 * Publishes the bytecode patch set into the resources the launcher jar is built
 * from.
 *
 * <p>This is the one thing that makes `java -jar server.jar` a complete
 * distribution: the patch set that turns a downloaded vanilla jar into a
 * VeltisMC server travels inside the launcher, under a name that says which
 * Minecraft version it addresses. An operator never has a `patches/` directory,
 * a Git checkout, a decompiler or a compiler, and never needs one.
 *
 * <p>Generated rather than assembled by the packaging script, so the file that
 * ships is the file the applier reads back and re-validates — a patch set that
 * this build could not read would fail here instead of on a stranger's machine.
 */
val publishBytecodePatch by tasks.registering {
    group = "minecraft"
    description = "Publishes the bytecode patch set the launcher jar distributes"
    val source = workspaceDir.file("build/veltis-patch.zip")
    inputs.file(source).withPropertyName("bytecodePatchSet")
    inputs.property("minecraftVersion", minecraftVersion)
    outputs.file(generatedPatchFile).withPropertyName("publishedPatchSet")
    dependsOn(prepareVeltisRuntime)
    doLast {
        val target = generatedPatchFile.get().asFile
        val version = "$minecraftVersion"
        target.parentFile.mkdirs()
        Files.copy(
            source.asFile.toPath(),
            target.toPath(),
            StandardCopyOption.REPLACE_EXISTING,
        )
        logger.lifecycle(
            "[Veltis] Published {} ({} bytes) as META-INF/veltis/patches/{}.zip",
            source.asFile,
            target.length(),
            version,
        )
    }
}

/**
 * The per-stage chain, for an IDE and for a developer working on patches.
 *
 * <p>Not on the production path: `prepareVeltisRuntime` above builds the same
 * result through the engine's own staging, and `compileMinecraftJava` exists so
 * IntelliJ can resolve, navigate and debug the patched sources with a real
 * Gradle compile classpath rather than a folder someone marked by hand.
 */
val prepareMinecraft by tasks.registering {
    group = "minecraft"
    description = "Downloads, decompiles, patches and compiles Minecraft $minecraftVersion (IDE path)"
    dependsOn(applyVeltisPatches, ":compileMinecraftJava", processMinecraftResources)
}

