// Data and module patches address resources, not code. Only the delta is copied:
// the vanilla jar already carries Minecraft's own resources, and copying them
// again would be a second set of identical bytes that could win over a patched
// one purely on classpath order. `VeltisRuntime.copyResourceDelta` does the same
// thing at runtime, so the two produce the same tree.
val processMinecraftResources = tasks.named<ProcessResources>("processMinecraftResources") {
    group = "minecraft"
    description = "Copies the resources the data and module patches changed"
    from(patchTargets("data"))
    from(patchTargets("modules"))
    destinationDir = resourcesDir.asFile
    dependsOn(":applyVeltisPatches")
}

