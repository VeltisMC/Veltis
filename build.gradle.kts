// ---------------------------------------------------------------------------
// The `minecraft` source set
//
// A real Gradle source set rather than an `idea { module { sourceDirs } }`
// edit, which is what made IntelliJ require a manual "Mark Sources Root" and
// go stale the moment the version changed. The source root is declared
// unconditionally, so an IDE opened before the first pipeline run still has the
// right folder registered; it simply stays empty until the pipeline fills it.
//
// The compile task is scoped to the files the patch set actually addresses
// rather than the whole tree. Decompiling Minecraft does not produce sources
// that compile wholesale, and compiling all ~15 000 of them to discover that is
// not useful. Unpatched classes come from the widened server jar at runtime, so
// the compiled output is exactly the delta the patches introduce.
// ---------------------------------------------------------------------------
val minecraft by sourceSets.creating {
    java.setSrcDirs(listOf(patchedDir.asFile))
    resources.setSrcDirs(emptyList<File>())
    // A real classpath. The empty `files()` this replaces is the other half of
    // the IntelliJ problem: with no classpath, every reference from a patched
    // file into Minecraft, into VeltisMC's own modules, or into a library is
    // unresolvable, so autocomplete and Ctrl+Click could not work however the
