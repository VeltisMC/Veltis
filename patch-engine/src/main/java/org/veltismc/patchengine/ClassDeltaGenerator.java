    /**
     * Generates flag-only deltas for the vanilla classes {@link AccessRequirements}
     * marked as needing rewrites. Each delta's header and inner-class entries
     * change when the class itself needed widening, and every flagged member
     * gets its recorded flags; bodies are never carried — the merged class is
     * the vanilla class with those flags rewritten, which is verified the same
     * way a compiled class's delta is.
     *
     * @param vanillaClasses     entry name → bytes for the baseline
     * @param analysis           which classes and members need rewriting
     * @param minecraftVersion   the version string recorded in each delta
     * @param shulkerFingerprint the source-patch fingerprint recorded in each
     * @return one class-delta entry per target, sorted by name
     */
    public static List<BytecodePatch.ProducedEntry> wideningDeltas(
            Map<String, byte[]> vanillaClasses, AccessRequirements.Result analysis,
            String minecraftVersion, String shulkerFingerprint) {
        Objects.requireNonNull(vanillaClasses, "vanillaClasses cannot be null");
        Objects.requireNonNull(analysis, "analysis cannot be null");
        var targets = new TreeSet<String>(analysis.wideningRequired());
        targets.addAll(analysis.memberWidenings().keySet());
        var entries = new ArrayList<BytecodePatch.ProducedEntry>();
        for (var target : targets) {
            var vanilla = vanillaClasses.get(target + ".class");
            if (vanilla == null) {
                continue;
            }
            entries.add(wideningDelta(vanilla, target, analysis.wideningRequired().contains(target),
                analysis.memberWidenings().getOrDefault(target, List.of()),
                minecraftVersion, shulkerFingerprint));
        }
        return entries;
    }

    private static BytecodePatch.ProducedEntry wideningDelta(byte[] vanillaBytes, String target,
                                                             boolean widenHeader,
                                                             List<AccessRequirements.MemberWidening> records,
                                                             String minecraftVersion,
                                                             String shulkerFingerprint) {
        var vanillaNode = parse(vanillaBytes, target);
        var isEnum = (vanillaNode.access & Opcodes.ACC_ENUM) != 0;
        var isInterface =
            (vanillaNode.access & (Opcodes.ACC_INTERFACE | Opcodes.ACC_ANNOTATION)) != 0;
        var widened = new ArrayList<ClassDelta.WidenedMember>(records.size());
        for (var record : records) {
            var access = memberAccess(vanillaNode, record);
            int rewritten;
            if (record.finalStrip()) {
                if ((access & Opcodes.ACC_FINAL) == 0) {
                    throw mismatch(target, "cannot drop final from member " + record.name()
                            + record.desc() + " because the vanilla class does not declare it"
                            + " final",
                        "the analysis and the vanilla jar disagree about the same bytes;"
                            + " the patch set cannot be cut from them");
                }
                rewritten = access & ~Opcodes.ACC_FINAL;
            } else if (record.field()) {
                rewritten = AccessWidener.widenAll(access, isInterface);
            } else {
                rewritten = AccessWidener.widenMethod(access, isEnum, record.name());
            }
            if (rewritten == access) {
                throw mismatch(target, "needs member " + record.name() + record.desc()
                        + " widened, but its flags are fixed by the class file format"
                        + " (current flags: 0x" + Integer.toHexString(access) + ")",
                    "an enum constructor must stay non-public and a static initialiser must"
                        + " stay package-private; widening either produces a class file the JVM"
                        + " rejects, so the reference cannot be served"
                        + "\n  Fix: avoid the reference that requires this widening");
            }
            widened.add(new ClassDelta.WidenedMember(record.field(), record.name(),
                record.desc(), rewritten));
        }

        var vanillaSha = BytecodePatch.sha256Hex(vanillaBytes);
        var placeholder = ClassDelta.placeholderHash();
        var deltaNode = buildWideningDelta(vanillaNode, widenHeader, widened,
            new ClassDelta.Metadata(ClassDelta.FORMAT, minecraftVersion, target, vanillaSha,
                placeholder, shulkerFingerprint, placeholder, List.of(), widened));
        var firstPass = ClassDelta.applyForGeneration(vanillaBytes, serialize(deltaNode));
        var merged = firstPass.bytes();
        var patchedSha = BytecodePatch.sha256Hex(merged);
        var fingerprint = ClassDelta.classPatchFingerprint(vanillaSha, patchedSha, target);
        var finalMeta = new ClassDelta.Metadata(ClassDelta.FORMAT, minecraftVersion, target,
            vanillaSha, patchedSha, shulkerFingerprint, fingerprint, List.of(), widened);
        deltaNode.attrs = new ArrayList<>(List.of(ClassDelta.attribute(finalMeta)));
        var deltaBytes = serialize(deltaNode);
        var applied = ClassDelta.apply(vanillaBytes, deltaBytes);
        if (!Arrays.equals(applied.bytes(), merged)) {
            throw mismatch(target, "is not deterministic: applying it twice produced different"
                + " bytes",
                "the widening delta was built from unstable inputs");
        }
        verifyWideningOnly(applied.bytes(), vanillaBytes, target, widenHeader, widened);
        return new BytecodePatch.ProducedEntry(target + ".class", BytecodePatch.Kind.CLASS,
            deltaBytes, vanillaSha, patchedSha);
    }

    private static ClassNode buildWideningDelta(ClassNode vanilla, boolean widenHeader,
                                                List<ClassDelta.WidenedMember> widened,
                                                ClassDelta.Metadata metadata) {
        var delta = new ClassNode();
        delta.version = vanilla.version;
        delta.access = widenHeader ? AccessWidener.widenClassAccess(vanilla.access)
            : vanilla.access;
        delta.name = vanilla.name;
        delta.signature = vanilla.signature;
        delta.superName = vanilla.superName;
        delta.interfaces = vanilla.interfaces != null ? vanilla.interfaces : new ArrayList<>();
        ClassDelta.copyScalars(vanilla, delta);
        delta.innerClasses = widenInnerEntries(vanilla.innerClasses);
        delta.nestMembers = vanilla.nestMembers;
        delta.fields = new ArrayList<>();
        delta.methods = new ArrayList<>();
        delta.attrs = new ArrayList<>(List.of(ClassDelta.attribute(metadata)));
        return delta;
    }

    /**
     * Mirrors {@link AccessWidener}'s treatment of inner-class entries: when a
     * class's header widens, so do the entries its own class file records for
     * its nested classes — the entries are what the compiler and the runtime
     * consult for a nested class's access.
     */
    private static List<InnerClassNode> widenInnerEntries(List<InnerClassNode> entries) {
        if (entries == null) {
            return null;
        }
        var widened = new ArrayList<InnerClassNode>(entries.size());
        for (var entry : entries) {
            widened.add(new InnerClassNode(entry.name, entry.outerName, entry.innerName,
                AccessWidener.widenAll(entry.access, false)));
        }
        return widened;
    }

    private static int memberAccess(ClassNode vanilla, AccessRequirements.MemberWidening record) {
        if (record.field()) {
            for (var field : vanilla.fields) {
                if (field.name.equals(record.name()) && field.desc.equals(record.desc())) {
                    return field.access;
                }
            }
        } else {
            for (var method : vanilla.methods) {
                if (method.name.equals(record.name()) && method.desc.equals(record.desc())) {
                    return method.access;
                }
            }
        }
        throw mismatch(vanilla.name, "needs member " + record.name() + record.desc()
                + " rewritten, which the vanilla class does not declare",
            "the analysis and the vanilla jar disagree about the same bytes; the patch set"
                + " cannot be cut from them");
    }

    /**
     * Verifies a widening delta the way a compiled class's delta is verified,
     * against the vanilla class instead of a compiled one: the merged class
     * must be the vanilla class — same header version, name, superclass,
     * interfaces, metadata, nest members and member bodies — with exactly the
     * documented flag changes: the rewritten header, the rewritten
     * inner-class entries, and the recorded member flags.
     */
    private static void verifyWideningOnly(byte[] mergedBytes, byte[] vanillaBytes,
                                           String target, boolean widenHeader,
                                           List<ClassDelta.WidenedMember> widened) {
        var merged = parseCompare(mergedBytes, target);
        var vanilla = parseCompare(vanillaBytes, target);
        var expectedHeader = widenHeader ? AccessWidener.widenClassAccess(vanilla.access)
            : vanilla.access;
        if (merged.version != vanilla.version
                || !Objects.equals(merged.name, vanilla.name)
                || !Objects.equals(merged.superName, vanilla.superName)
                || !Objects.equals(merged.interfaces, vanilla.interfaces)) {
            throw mismatch(target, "produced a header that differs from the vanilla class in"
                    + " more than its access flags",
                "a widening delta rewrites flags and nothing else");
        }
        if (merged.access != expectedHeader) {
            throw mismatch(target, "produced access flags 0x"
                    + Integer.toHexString(merged.access) + " but expected 0x"
                    + Integer.toHexString(expectedHeader),
                "the header must be the vanilla flags with exactly the required widening");
        }
        if (!Arrays.equals(ClassDelta.scalarShell(merged), ClassDelta.scalarShell(vanilla))) {
            throw mismatch(target, "produced class metadata that differs from the vanilla"
                    + " class",
                "a widening delta rewrites flags and nothing else");
        }
        var vanillaEntries = vanilla.innerClasses;
        var mergedEntries = merged.innerClasses;
        var expectedEntryCount = vanillaEntries == null ? 0 : vanillaEntries.size();
        var actualEntryCount = mergedEntries == null ? 0 : mergedEntries.size();
        if (actualEntryCount != expectedEntryCount) {
            throw mismatch(target, "produced " + actualEntryCount + " inner-class entries but"
                    + " the vanilla class has " + expectedEntryCount,
                "a widening delta rewrites flags and nothing else");
        }
        for (var i = 0; i < expectedEntryCount; i++) {
            var want = vanillaEntries.get(i);
            var got = mergedEntries.get(i);
            var wantAccess = widenHeader ? AccessWidener.widenAll(want.access, false)
                : want.access;
            if (!Objects.equals(want.name, got.name)
                    || !Objects.equals(want.outerName, got.outerName)
                    || !Objects.equals(want.innerName, got.innerName)
                    || wantAccess != got.access) {
                throw mismatch(target, "produced an inner-class entry for " + want.name
                        + " with access 0x" + Integer.toHexString(got.access)
                        + " but expected 0x" + Integer.toHexString(wantAccess),
                    "inner-class entries change only when the class's own header widens");
            }
        }
        if (!Objects.equals(merged.nestMembers, vanilla.nestMembers)
                && !Objects.equals(merged.nestMembers == null ? List.of() : merged.nestMembers,
                    vanilla.nestMembers == null ? List.of() : vanilla.nestMembers)) {
            throw mismatch(target, "produced nest members " + merged.nestMembers
                    + " but the vanilla class declares " + vanilla.nestMembers,
                "a widening delta rewrites flags and nothing else");
        }

        var records = new HashMap<ClassDelta.MemberRef, Integer>();
        for (var record : widened) {
            records.put(new ClassDelta.MemberRef(record.field(), record.name(), record.desc()),
                record.access());
        }
        if (merged.fields.size() != vanilla.fields.size()
                || merged.methods.size() != vanilla.methods.size()) {
            throw mismatch(target, "produced a different member count than the vanilla class"
                    + " (" + merged.fields.size() + "/" + merged.methods.size() + " vs "
                    + vanilla.fields.size() + "/" + vanilla.methods.size() + ")",
                "a widening delta rewrites flags and nothing else");
        }
        var isEnum = (vanilla.access & Opcodes.ACC_ENUM) != 0;
        var isInterface =
            (vanilla.access & (Opcodes.ACC_INTERFACE | Opcodes.ACC_ANNOTATION)) != 0;
        for (var i = 0; i < vanilla.fields.size(); i++) {
            var want = vanilla.fields.get(i);
            var got = merged.fields.get(i);
            var key = new ClassDelta.MemberRef(true, want.name, want.desc);
            if (!Objects.equals(want.name, got.name) || !Objects.equals(want.desc, got.desc)) {
                throw mismatch(target, "produced a different member order than the vanilla"
                        + " class",
                    "with no carried members the merged member list must be the vanilla list");
            }
            var expectedAccess = records.getOrDefault(key, want.access);
            if (got.access != expectedAccess) {
                throw mismatch(target, "declares field " + want.name + want.desc
                        + " with access 0x" + Integer.toHexString(got.access)
                        + " but expected 0x" + Integer.toHexString(expectedAccess),
                    "the delta's recorded flags must be applied verbatim");
            }
            if (!Arrays.equals(canonicalField(got, isInterface),
                    canonicalField(want, isInterface))) {
                throw mismatch(target, "produced field " + want.name + want.desc
                        + " whose definition differs from the vanilla class",
                    "a widening delta rewrites flags and nothing else");
            }
        }
        for (var i = 0; i < vanilla.methods.size(); i++) {
            var want = vanilla.methods.get(i);
            var got = merged.methods.get(i);
            var key = new ClassDelta.MemberRef(false, want.name, want.desc);
            if (!Objects.equals(want.name, got.name) || !Objects.equals(want.desc, got.desc)) {
                throw mismatch(target, "produced a different member order than the vanilla"
                        + " class",
                    "with no carried members the merged member list must be the vanilla list");
            }
            var expectedAccess = records.getOrDefault(key, want.access);
            if (got.access != expectedAccess) {
                throw mismatch(target, "declares method " + want.name + want.desc
                        + " with access 0x" + Integer.toHexString(got.access)
                        + " but expected 0x" + Integer.toHexString(expectedAccess),
                    "the delta's recorded flags must be applied verbatim");
            }
            if (!Arrays.equals(canonicalMethod(got, isEnum),
                    canonicalMethod(want, isEnum))) {
                throw mismatch(target, "produced method " + want.name + want.desc
                        + " whose definition differs from the vanilla class",
                    "a widening delta rewrites flags and nothing else");
            }
        }
    }

